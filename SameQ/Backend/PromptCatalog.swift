    /// フォールバック候補（F27 / 受け入れ条件 3）。
    ///
    /// 「生成に失敗した日でも必ず何らかのお題が有効になる」ことを担保するため、
    /// 候補プールが全滅した場合に使う、常に安全だと分かっているお題。
