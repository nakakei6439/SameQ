        array[
            'いま食べたいものは「温かいごはん」。理由は説明できないけれど、迷いなくそれが出る。',
            'いま好きな時間は、家族みんながそれぞれ別々のことをしているのに、同じ部屋にいる時間。',
            '頭の中でずっと同じ曲がリフレインしてる。嫌じゃないので、このまま流す。',
            '好きな景色は、帰りの電車から見えた、最後のほうの空。街の灯がぼんやり灯り始めた瞬間が好き。',
            '自分のためにそっと買えるとしたら、厚みのあるノートを一冊。書くかどうかは決めてない。'
