-- SameQ 緊急修正: 運営回答が「その日のお題と無関係」になっていたのを直す
--
-- ## 何が起きていたか
--
-- `ensure_official_answers()` は、48件だったころのお題プール（`v_pool`）の件数から
-- `v_start_idx` を計算し、その添字で `v_categories[]` を引いて意味カテゴリを決めていた。
-- 「`ensure_todays_prompt()` と一字一句同じプール」であることが前提の作りだった。
--
-- ところが **スプリント19（migration 20260908000001）で `ensure_todays_prompt()` の
-- プールが 999 件に拡張された**とき、この関数は一切更新されなかった。
-- その結果、お題は 999 件から選ばれ、カテゴリは 48 件の添字から選ばれる、という
-- まったく無関係な2つの計算になった。
--
-- 実害（2026-09-22 に本番で確認）:
--   お題       : 「誰にも言っていないけれど本当は少し気になっていることは？」
--   運営回答   : 「財布の中に、たまたま入っていた500円玉でコンビニのコーヒーを買えた。」など
--                カテゴリ0（その日の小さな救われた瞬間）の5件
--   → **どれも質問に答えていない。** スプリント19を適用した 2026-09-09/10 以降、毎日この状態。
--
-- ## 直し方
--
-- プール件数どうしを同期させ続けるのは、また同じ事故を起こす。
-- **その日の実際のお題テキストからカテゴリを引く**方式に変える。
-- 999件のお題は8つのカテゴリのテンプレートから生成されており、文頭がカテゴリを表している
-- （「今日」「最近」「いま」「小さい頃」「もし」「この一年」…）ので、前方一致で決まる。
-- これで `v_pool` への依存そのものが消え、お題プールを何件に増やしても壊れない。
--
-- 内訳（999件の文頭を集計）:
--   いま 253 / 今日 174 / もし一日だけ 146 / 小さい頃 141 / 最近 118 / この一年で 77 /
--   残り約90件（「誰にも言って」「誰にも話して」「「なんでもな」等）は内省系 → カテゴリ7
--
-- お題が `public.prompts` にまだ無いときは何もしないで戻る（以前は外部キー違反で落ちていた）。

