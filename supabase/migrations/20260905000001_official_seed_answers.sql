            v_prompt_id,
            v_official_ids[i],
            v_body_by_category[v_category + 1][i],
            'ja'
        )
        on conflict (prompt_id, author_id) do nothing;
        -- `do nothing` のときは 0、挿入できたときは 1。GET DIAGNOSTICS は
        -- 代入文の右辺に式を取れないので、いったん `v_rc` で受けてから累積する。
        get diagnostics v_rc = row_count;
        v_inserted := v_inserted + v_rc;
    end loop;

    raise notice 'ensure_official_answers: prompt=% category=% new_or_existed_inserts=%', v_prompt_id, v_category, v_inserted;
end;
$$;

