-- SameQ 単発対応: 本番タイムラインの恒久シードとして「運営回答」を自己修復で補充する
-- (2026-09-05)
--
-- 背景:
--   Apple App Review から build 6 で Guideline 2.1(a) 「他ユーザーの投稿を確認する
--   方法がない」との理由で2度目のリジェクトを受けた (2026-09-05)。原因は
--   `public.world_timeline` (migration 20260818000003) の where 句が「自分が
--   そのお題に回答済みでなければ0件」を強制しており、かつ本番に恒久的なサンプル
--   投稿の仕組みが無いこと。実ユーザーがまだ少ない現状、毎日必ず「まだ誰も答えて
--   いません」の空状態になっていた。
--
--   過去の `supabase/seed.sql` は `now()` 相対の一度きりシードで、投入から 26〜54
--   時間で期限切れになる運用だった。Apple の再審査タイミングは予測できず、お題は
--   日次でローテーションするため、一度きりの手動シードでは同じ理由で再度リジェクト
--   され得る構造になっていた。
--
-- 対応方針:
--   `ensure_todays_prompt()` (migration 20260829000013 / 20260830000014) と同じ
--   「気づいたクライアントが自己修復する」パターンで `ensure_official_answers()`
--   関数を追加する。pg_cron は本番で未有効化 (`cron.job` テーブル非存在) のため、
--   クライアント起点の自己修復に依存する設計を維持する。
--
--   * 5件の固定「運営」アカウントを `public.users` に常設する (ニックネーム共通)。
--     実ユーザー (匿名) と区別がつく固定パターン (emoji + nickname) にする。
--     実投稿が増えてくれば自然にタイムラインのなかに埋もれる。
--   * `ensure_todays_prompt()` と**完全に同じ** `v_day_key` / `v_day_index` /
--     `v_start_idx` 計算式で「今日のお題の pool index (0〜47)」を再導出し、
--     その index に対応する 8 つの意味カテゴリ (0〜7) のいずれかに分類する。
--   * 5 アカウント分の `posts` を `on conflict (prompt_id, author_id) do nothing` で
--     冪等に投入する。`expires_at` は手動計算せず、既存の `posts_set_expiry` トリガー
--     (migration 20260817000002) に任せる。
--
-- 冪等性:
--   * users insert: `on conflict (id) do nothing`
--   * posts insert: `on conflict (prompt_id, author_id) do nothing`
--   これで何度呼ばれても結果は同じ (5 アカウント × 1 お題 = 5 件で頭打ち)。
--
-- セキュリティ:
--   * `security definer` で他人の `auth.uid()` 経由で user_id を詐称して挿入される
--     のを防ぐ。`posts_insert_own` ポリシー (migration 20260817000001) は
--     `author_id = auth.uid()` を要求するため、通常ユーザーとして
--     `author_id = '<official UUID>'` の行を INSERT しようとするとポリシー違反に
--     なる。`security definer` で RLS を迂回することでこれを回避している。
--   * 関数実行者は認証済みユーザーなら誰でも可 (`grant execute ... to authenticated`)。
-- ---------------------------------------------------------------------------

