    -- トリガーは `prompt is not active` 例外を投げるので、お題が有効でない
    -- (まだ未生成 / 終了済み) ときはループ全体を抜けて例外がそのまま伝播する
    -- (呼び出し元 SupabaseBackend.promptState() は try? で握り潰す)。
